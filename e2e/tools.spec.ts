  test('paste an image from the clipboard', async ({ page }) => {
    await gotoEditor(page)
    await openFiles(page, [FIX('sample.pdf')])
    await page.evaluate(async () => {
      const c = document.createElement('canvas'); c.width = 40; c.height = 30
      const ctx = c.getContext('2d')!; ctx.fillStyle = '#0a0'; ctx.fillRect(0, 0, 40, 30)
      const blob: Blob = await new Promise((r) => c.toBlob((b) => r(b!), 'image/png'))
      const dt = new DataTransfer(); dt.items.add(new File([blob], 'clip.png', { type: 'image/png' }))
      document.dispatchEvent(new ClipboardEvent('paste', { clipboardData: dt, bubbles: true, cancelable: true }))
    })
    await expect(objs(page, 'image')).toHaveCount(1)
  })

