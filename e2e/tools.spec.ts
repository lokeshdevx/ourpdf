test.describe('OCR @cross', () => {
  test('recognises text in an image locally, offers search, copy and searchable-PDF export', async ({ page }) => {
    test.setTimeout(240000)
    const external: string[] = []
    page.on('request', (r) => { const u = new URL(r.url()); if (!['localhost', '127.0.0.1'].includes(u.hostname) && !['data:', 'blob:'].includes(u.protocol)) external.push(r.url()) })
    await gotoEditor(page)
    await page.getByTestId('onboarding-images').click()
    const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.getByTestId('images-add').click()])
    await chooser.setFiles(FIX('ocr-text.png'))
    await page.getByTestId('images-run').click()
    await page.waitForSelector('[data-testid=pdf-page] canvas', { timeout: 30000 })
    await runCommand(page, 'ocr.run')
    await expect(page.getByTestId('lang-eng')).toBeVisible()
    await page.getByTestId('ocr-run').click()
    await expect(page.getByTestId('ocr-results')).toBeVisible({ timeout: 200000 })
    const text = await page.getByTestId('ocr-text').inputValue()
    expect(text.toLowerCase()).toContain('hello')
    expect(text.toLowerCase()).toContain('invoice')
    // searchable PDF export contains the recognised words as text
    const [dl] = await Promise.all([page.waitForEvent('download'), page.getByTestId('ocr-searchable').click()])
    const t = (await pdfTexts(await downloadBytes(dl))).join(' ').toLowerCase()
    expect(t).toContain('hello')
    // search finds OCR text in the viewer
    await page.keyboard.press('Escape')
    await page.keyboard.press('Control+f')
    await page.getByTestId('search-input').fill('invoice')
    await expect(page.getByTestId('search-count')).toContainText('1 of', { timeout: 15000 })
    expect(external).toEqual([]) // no request left this origin (language data & engine are self-hosted)
  })

  test('OCR can be cancelled', async ({ page }) => {
    test.setTimeout(120000)
    await gotoEditor(page)
    await openFiles(page, [FIX('large-500.pdf')])
    await runCommand(page, 'ocr.run')
    await page.getByTestId('scope-select').click()
    await page.getByRole('option', { name: 'All pages' }).click()
    await page.getByTestId('ocr-run').click()
    await expect(page.getByTestId('ocr-cancel')).toBeVisible({ timeout: 30000 })
    await page.getByTestId('ocr-cancel').click()
    await expect(page.getByTestId('ocr-run')).toBeVisible({ timeout: 30000 })
  })
})
