    await page.getByLabel('Tooltip').fill('Your email')
    await page.getByRole('checkbox', { name: /Required/ }).or(page.getByLabel('Required')).first().click().catch(() => {})
    await runCommand(page, 'form.field-checkbox')
    await dragOnPage(page, [0.15, 0.78], [0.2, 0.8])
    await expect(objs(page, 'field')).toHaveCount(2)
    // fill mode + validation
    await runCommand(page, 'form.fill')
