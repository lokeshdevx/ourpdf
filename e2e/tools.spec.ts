    await page.getByTestId('link-url').fill('https://example.com/docs')
    await page.getByTestId('link-save').click()
    const doc = await PDFDocument.load(await saveAndGetBytes(page), { updateMetadata: false })
    const annots = doc.getPage(0).node.Annots()!
    const a = annots.lookup(0) as import('pdf-lib').PDFDict
    expect(a.get(PDFName.of('Subtype'))!.toString()).toBe('/Link')
